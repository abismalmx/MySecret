/**
 * MySecret - Obsidian Transparent Encryption Plugin
 * WebAuthn Assertion & Registration Verification
 *
 * Shared cryptographic verification helpers used by BOTH WebAuthn based
 * biometric providers (`webauthn` and `external-bridge`).
 *
 * WHY THIS MODULE EXISTS
 * ----------------------
 * The WebAuthn PRF extension is only a secret *transport*: it returns opaque
 * bytes that the authenticator computes after a user-verifying ceremony. The
 * bytes themselves are NOT proof of anything. If a caller accepts them without
 * checking the surrounding assertion, then whoever produced them (the page,
 * the bridge web app, a malicious script) can hand over ANY value and the
 * wrapping key becomes attacker-chosen.
 *
 * The only thing that proves "this secret came from the enrolled
 * authenticator, after a real biometric check" is the ASSERTION SIGNATURE:
 *
 *   signature = Sign(credentialPrivateKey, authenticatorData || SHA-256(clientDataJSON))
 *
 * Therefore every provider MUST verify:
 *
 *   1. The assertion was produced by the ENROLLED credential (id match).
 *   2. The ceremony was USER VERIFIED (the UV flag in the authenticator data
 *      AND the `userVerified` flag of the response).
 *   3. The challenge is the fresh one generated by the relying party
 *      (replay protection).
 *   4. The origin is the expected one (phishing protection).
 *   5. The RP ID hash matches the expected relying party (so a credential
 *      created for another site cannot be replayed here).
 *   6. The signature verifies against the stored credential public key.
 *
 * Without this, the whole biometric gate is decorative.
 */

import { base64UrlToBytes, bytesToBase64Url, constantTimeEqual } from '../utils/buffer';

/**
 * Minimum accepted length of a PRF output.
 *
 * The PRF extension is defined on top of HMAC-SHA-256, so a legitimate
 * authenticator returns exactly 32 bytes.
 *
 * SECURITY: a ZERO-LENGTH output must never be accepted. If the browser
 * returns the PRF value as a base64url STRING (as some implementations do)
 * and the caller blindly does `new Uint8Array(string)`, the result is an EMPTY
 * buffer whose SHA-256 is a PUBLIC CONSTANT. The wrapping key would then be
 * known to anybody, and the vault key could be recovered from the on-disk
 * envelope without any biometric check at all.
 */
export const MIN_PRF_SECRET_LENGTH = 32;

/** CTAP2 authenticator data flags. */
const FLAG_USER_PRESENT = 0x01;
const FLAG_USER_VERIFIED = 0x04; // Bit 2: UV (User Verified)

/** Minimum length of the authenticator data (32 byte hash + 1 byte flags). */
const MIN_AUTHENTICATOR_DATA_LENGTH = 33;

/**
 * Normalizes the PRF extension output into raw bytes.
 *
 * The WebAuthn IDL defines `AuthenticationExtensionsPRFValues.first` as a
 * `BufferSource`, but the *JSON* flavour of the same dictionary
 * (`AuthenticationExtensionsPRFValuesJSON`) uses a `Base64URLString`, and
 * browsers have shipped both behaviours over time. To stay safe (and to never
 * silently degrade to an empty secret) BOTH encodings are accepted and the
 * result MUST be at least {@link MIN_PRF_SECRET_LENGTH} bytes long.
 *
 * @throws Error when the value cannot be interpreted or is too short.
 */
export function normalizePrfOutput(value: unknown): Uint8Array {
  let bytes: Uint8Array | null = null;

  if (value instanceof ArrayBuffer) {
    bytes = new Uint8Array(value);
  } else if (ArrayBuffer.isView(value)) {
    const view = value as ArrayBufferView;
    bytes = new Uint8Array(view.buffer, view.byteOffset, view.byteLength);
  } else if (typeof value === 'string') {
    // Base64URL encoded form (the JSON flavour of the extension output).
    bytes = base64UrlToBytes(value);
  }

  if (!bytes) {
    throw new Error('El autenticador no devolvió un resultado PRF válido.');
  }
  if (bytes.length < MIN_PRF_SECRET_LENGTH) {
    throw new Error(
      'El resultado PRF del autenticador es demasiado corto: la verificación biométrica no es posible.'
    );
  }
  return bytes;
}

/**
 * Computes the SHA-256 digest of a buffer.
 */
export async function sha256Bytes(data: Uint8Array): Promise<Uint8Array> {
  const digest = await window.crypto.subtle.digest('SHA-256', data as BufferSource);
  return new Uint8Array(digest);
}

/**
 * Converts a DER-encoded ECDSA signature (as produced by WebAuthn for the
 * ES256 algorithm) into the raw `r || s` format expected by the WebCrypto
 * `ECDSA` verifier.
 *
 * WebAuthn serializes the signature as an ASN.1 `SEQUENCE { INTEGER r,
 * INTEGER s }`, while WebCrypto always uses the fixed-length P1363 form.
 */
export function derToRawEcdsaSignature(der: Uint8Array): Uint8Array {
  let offset = 0;

  const readLength = (): number => {
    if (offset >= der.length) throw new Error('Firma ECDSA DER truncada.');
    let length = der[offset++];
    if ((length & 0x80) !== 0) {
      const count = length & 0x7f;
      if (count === 0 || count > 4 || offset + count > der.length) {
        throw new Error('Firma ECDSA DER con longitud inválida.');
      }
      length = 0;
      for (let i = 0; i < count; i++) {
        length = (length << 8) | der[offset++];
      }
    }
    return length;
  };

  const readInteger = (): Uint8Array => {
    if (offset >= der.length || der[offset++] !== 0x02) {
      throw new Error('Firma ECDSA DER mal formada.');
    }
    const length = readLength();
    if (offset + length > der.length) {
      throw new Error('Firma ECDSA DER truncada.');
    }
    const value = der.slice(offset, offset + length);
    offset += length;
    return value;
  };

  if (offset >= der.length || der[offset++] !== 0x30) {
    throw new Error('Firma ECDSA DER mal formada.');
  }
  readLength(); // Length of the SEQUENCE (the elements are read below).

  const r = readInteger();
  const s = readInteger();

  // Strip the leading zero bytes DER adds for positive integers, then
  // left-pad to the fixed 32-byte width.
  const normalize = (value: Uint8Array): Uint8Array => {
    let start = 0;
    while (start < value.length - 1 && value[start] === 0x00) start++;
    const out = new Uint8Array(32);
    const slice = value.slice(start);
    if (slice.length > 32) {
      // Truncating would be wrong: reject instead.
      throw new Error('Componente de la firma ECDSA fuera de rango.');
    }
    out.set(slice, 32 - slice.length);
    return out;
  };

  const raw = new Uint8Array(64);
  raw.set(normalize(r), 0);
  raw.set(normalize(s), 32);
  return raw;
}

/**
 * Imports a stored SPKI public key for signature verification.
 *
 * Both algorithm families accepted at enrollment time are supported:
 * ES256 (ECDSA P-256) and RS256 (RSASSA-PKCS1-v1_5 with SHA-256).
 */
async function importVerificationKey(spki: Uint8Array): Promise<CryptoKey> {
  try {
    return await window.crypto.subtle.importKey(
      'spki',
      spki as BufferSource,
      { name: 'ECDSA', namedCurve: 'P-256' },
      false,
      ['verify']
    );
  } catch {
    // Not an ECDSA key: fall through to RSA.
  }

  try {
    return await window.crypto.subtle.importKey(
      'spki',
      spki as BufferSource,
      { name: 'RSASSA-PKCS1-v1_5', hash: 'SHA-256' },
      false,
      ['verify']
    );
  } catch {
    throw new Error('La clave pública de la credencial no es válida.');
  }
}

/**
 * Converts a `BufferSource` into a `Uint8Array` without copying when it is
 * already a view over the exact bytes.
 *
 * It also handles the (illegal but possible) case of a `Uint8Array` that is a
 * VIEW over a larger buffer: the exact slice is used, never the whole buffer.
 */
export function toUint8Array(source: ArrayBuffer | ArrayBufferView): Uint8Array {
  if (source instanceof ArrayBuffer) {
    return new Uint8Array(source);
  }
  if (ArrayBuffer.isView(source)) {
    const view = source as ArrayBufferView;
    return new Uint8Array(view.buffer as ArrayBuffer, view.byteOffset, view.byteLength);
  }
  throw new Error('Buffer de origen inválido.');
}

/**
 * The subset of a WebAuthn assertion that has to be verified.
 */
export interface AssertionLike {
  id: string;
  response: {
    authenticatorData?: ArrayBuffer | ArrayBufferView | null;
    clientDataJSON?: ArrayBuffer | ArrayBufferView | null;
    signature?: ArrayBuffer | ArrayBufferView | null;
    userVerified?: boolean;
  };
}

export interface AssertionVerificationOptions {
  /** Base64URL identifier of the ENROLLED credential. */
  expectedCredentialId: string;
  /** The fresh challenge generated by the relying party. */
  expectedChallenge: Uint8Array;
  /** The origin the ceremony must have been performed on (e.g. `https://x.pages.dev`). */
  expectedOrigin: string;
  /** The relying party id (a registrable domain suffix of the origin). */
  expectedRpId: string;
  /** The SPKI public key of the enrolled credential (base64 encoded). */
  publicKeySpkiBase64: string;
}

/**
 * Verifies a WebAuthn assertion.
 *
 * @throws Error when any of the checks fails. The caller MUST fail closed.
 */
export async function verifyWebAuthnAssertion(
  assertion: AssertionLike,
  options: AssertionVerificationOptions
): Promise<void> {
  // --- 1. The assertion must come from the ENROLLED credential. ---
  let expectedIdBytes: Uint8Array;
  let actualIdBytes: Uint8Array;
  try {
    expectedIdBytes = base64UrlToBytes(options.expectedCredentialId);
    actualIdBytes = base64UrlToBytes(assertion.id);
  } catch {
    throw new Error('El identificador de la credencial no es válido.');
  }
  if (
    expectedIdBytes.length === 0 ||
    expectedIdBytes.length !== actualIdBytes.length ||
    !constantTimeEqual(expectedIdBytes, actualIdBytes)
  ) {
    throw new Error('La aserción no procede de la credencial registrada.');
  }

  const clientDataJSON = assertion.response?.clientDataJSON;
  const authenticatorData = assertion.response?.authenticatorData;
  const signature = assertion.response?.signature;
  if (!clientDataJSON || !authenticatorData || !signature) {
    throw new Error('La aserción biométrica está incompleta.');
  }

  // --- 2. The ceremony MUST have been user verified. ---
  const authData = toUint8Array(authenticatorData);
  if (authData.length < MIN_AUTHENTICATOR_DATA_LENGTH) {
    throw new Error('Los datos del autenticador son inválidos.');
  }
  const flags = authData[32];
  const isUserVerified = (flags & FLAG_USER_VERIFIED) !== 0 || assertion.response?.userVerified === true;
  if (!isUserVerified) {
    throw new Error('El autenticador no confirmó la verificación de usuario.');
  }

  // --- 3. The client data must belong to THIS ceremony and THIS origin. ---
  let clientData: any;
  try {
    clientData = JSON.parse(new TextDecoder().decode(toUint8Array(clientDataJSON)));
  } catch {
    throw new Error('Los datos de cliente de la aserción son ilegibles.');
  }
  if (!clientData || clientData.type !== 'webauthn.get') {
    throw new Error('El tipo de la ceremonia no es el esperado.');
  }
  if (typeof clientData.challenge !== 'string') {
    throw new Error('La aserción no incluye el desafío (challenge).');
  }
  const challengeBytes = base64UrlToBytes(clientData.challenge);
  const expectedChallenge = options.expectedChallenge;
  if (
    challengeBytes.length !== expectedChallenge.length ||
    !constantTimeEqual(challengeBytes, expectedChallenge)
  ) {
    throw new Error('El desafío de la aserción no coincide: posible ataque de repetición.');
  }
  if (typeof clientData.origin !== 'string' || clientData.origin !== options.expectedOrigin) {
    throw new Error('El origen de la aserción no es el esperado.');
  }

  // --- 4. The authenticator data must carry the UV flag and match the RP. ---
  if ((flags & FLAG_USER_PRESENT) === 0) {
    throw new Error('La ceremonia no pudo confirmar la presencia del usuario.');
  }
  if ((flags & FLAG_USER_VERIFIED) === 0) {
    throw new Error('La ceremonia no pudo confirmar la verificación biométrica.');
  }
  const rpIdHash = await sha256Bytes(new TextEncoder().encode(options.expectedRpId));
  if (!constantTimeEqual(authData.slice(0, 32), rpIdHash)) {
    throw new Error('La credencial pertenece a otra aplicación (RP ID incorrecto).');
  }

  // --- 5. The signature must verify against the enrolled public key. ---
  const spki = decodeBase64(options.publicKeySpkiBase64);
  if (spki.length === 0) {
    throw new Error('No hay clave pública de la credencial almacenada.');
  }
  const publicKey = await importVerificationKey(spki);

  const clientDataHash = await sha256Bytes(toUint8Array(clientDataJSON));
  const signedData = new Uint8Array(authData.length + clientDataHash.length);
  signedData.set(authData, 0);
  signedData.set(clientDataHash, authData.length);

  const signatureBytes = toUint8Array(signature);
  const isEcdsa = publicKey.algorithm.name === 'ECDSA';
  const signatureForVerify = isEcdsa ? derToRawEcdsaSignature(signatureBytes) : signatureBytes;

  let valid = false;
  try {
    valid = await window.crypto.subtle.verify(
      { name: publicKey.algorithm.name, hash: 'SHA-256' } as any,
      publicKey,
      signatureForVerify as BufferSource,
      signedData as BufferSource
    );
  } catch {
    valid = false;
  }
  if (!valid) {
    throw new Error('La firma de la aserción biométrica no es válida.');
  }
}

/**
 * Decodes a standard Base64 string into bytes.
 */
function decodeBase64(base64: string): Uint8Array {
  if (!base64) return new Uint8Array(0);
  try {
    const binary = atob(base64.replace(/\s+/g, ''));
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) {
      bytes[i] = binary.charCodeAt(i);
    }
    return bytes;
  } catch {
    return new Uint8Array(0);
  }
}

/**
 * The subset of a WebAuthn registration result that has to be validated.
 */
export interface RegistrationLike {
  id: string;
  response: {
    userVerified?: boolean;
    publicKey?: ArrayBuffer | ArrayBufferView | null;
  };
}

/**
 * Validates a freshly created WebAuthn credential.
 *
 * The attestation is NOT verified (the authenticator is a platform one and
 * there is no attestation trust anchor), but the credential MUST have been
 * user verified and its public key MUST be importable, otherwise the stored
 * envelope could never be verified later.
 *
 * @returns the SPKI public key of the new credential.
 */
export async function validateWebAuthnRegistration(
  credential: RegistrationLike
): Promise<Uint8Array> {
  if (!credential || !credential.id) {
    throw new Error('No se recibió una credencial biométrica válida.');
  }
  if (credential.response?.userVerified === false) {
    throw new Error(
      'El autenticador no confirmó la verificación de usuario: usa tu contraseña maestra.'
    );
  }
  const spki = credential.response?.publicKey;
  if (!spki) {
    throw new Error('La credencial biométrica no expuso su clave pública.');
  }
  const spkiBytes = toUint8Array(spki);
  // Importing proves the key is well formed and usable for verification.
  await importVerificationKey(spkiBytes);
  return spkiBytes;
}

/**
 * Encodes bytes as a Base64URL string (used to persist public keys).
 */
export function bytesToBase64UrlString(bytes: Uint8Array): string {
  return bytesToBase64Url(bytes);
}

/**
 * MySecret - Obsidian Transparent Encryption Plugin
 * External WebAuthn Biometric Bridge Provider
 *
 * Implements biometric authentication on platforms where embedded WebViews lack
 * native WebAuthn/Biometrics (e.g. Obsidian on Android).
 *
 * Flow:
 *  1. Obsidian generates an ephemeral ECDH (P-256) keypair and session token.
 *  2. Opens the external bridge URL in the system browser via `window.open(url, '_system')`.
 *  3. In Chrome/Android, user scans their fingerprint via WebAuthn PRF.
 *  4. The browser derives an ECDH shared secret, derives an AES-256-GCM key
 *     through HKDF and encrypts the PRF secret + the WebAuthn ASSERTION.
 *  5. Browser redirects back to `obsidian://mysecret-auth?session=...&pub=...&iv=...&tag=...&data=...`.
 *  6. Obsidian intercepts the callback, decrypts, VERIFIES the assertion
 *     signature against the enrolled credential public key, and only then
 *     unwraps the VaultKey.
 *
 * SECURITY MODEL (the subtle part)
 * ---------------------------------
 * The bridge web app is a REMOTE, THIRD-PARTY page. It runs in the browser
 * and it is the one that produces the PRF secret. If Obsidian trusted the
 * secret blindly, a compromised (or simply malicious) bridge could hand over
 * ANY 32 bytes and the vault key would be unwrapped without a biometric
 * check ever happening.
 *
 * The fix is the ASSERTION SIGNATURE: the browser also returns the full
 * WebAuthn assertion (authenticatorData, clientDataJSON and signature) and
 * Obsidian verifies it against the public key that was stored at enrollment
 * time. Because only the ENROLLED AUTHENTICATOR holds that private key, a
 * valid signature proves that the PRF secret was really produced by the
 * platform authenticator after a user-verifying ceremony.
 *
 * Additionally:
 *  - The shared secret goes through HKDF-SHA256 (NIST SP 800-56A) instead of
 *    being used directly as an AES key.
 *  - The AES-GCM AAD binds the protocol version, the session, the action and
 *    the vault (through a one-way binding, so the vault id itself never
 *    leaves the plugin), so a captured ciphertext cannot be replayed into
 *    another session, action or vault.
 *  - The session token is compared in constant time and every protocol
 *    parameter is validated (strict hex, exact lengths).
 *  - The RP ID and the origin are pinned in the envelope.
 */

import { BiometricProvider, DeviceBiometricEnvelope } from './types';
import {
  bytesToHex,
  hexToBytes,
  hexToBytesStrict,
  stringToBytes,
  base64ToBytes,
  constantTimeEqual
} from '../utils/buffer';
import { encryptAesGcm, decryptAesGcm, importAesKey } from '../crypto/aes';
import { zeroize } from '../utils/zeroize';
import {
  BIOMETRIC_ENVELOPE_VERSION,
  biometricAad,
  sha256Hex,
  constantTimeHexEqual,
  deriveAesKeyFromSecret
} from './kdf';
import {
  verifyWebAuthnAssertion,
  normalizePrfOutput
} from './webauthn-assertion';
import { computeRpId, computeOrigin } from './rp-id';
import { validateBridgeUrl } from './bridge-url';
import { sha256HexSync } from '../utils/sha256';

/**
 * Version of the bridge protocol.
 *
 * It is embedded in every message and in the AES-GCM AAD, so a downgrade to
 * an older (weaker) protocol cannot be performed silently.
 */
export const BRIDGE_PROTOCOL_VERSION = 2;

/** Expected length (hex characters) of the session token: 32 bytes. */
const SESSION_TOKEN_HEX_LENGTH = 64;

/** Expected length (hex characters) of an ECDH P-256 public key: 65 bytes. */
const ECDH_PUBLIC_KEY_HEX_LENGTH = 130;

/** Expected length (hex characters) of the PRF salt: 32 bytes. */
const PRF_SALT_HEX_LENGTH = 64;

/** Timeout of a pending ceremony. */
const BRIDGE_TIMEOUT_MS = 75000;

/**
 * The payload exchanged through the bridge, in cleartext inside the
 * AES-GCM envelope.
 */
interface BridgePayload {
  v: number;
  action: 'enroll' | 'verify';
  session: string;
  prfSecret: string;
  credentialId: string;
  /** Base64 encoded SPKI public key of the credential. */
  publicKey?: string;
  /** The WebAuthn assertion (for the `verify` action). */
  assertion?: {
    authenticatorData: string;
    clientDataJSON: string;
    signature: string;
    userVerified: boolean;
    /** The challenge the browser used, base64url encoded. */
    challenge: string;
  };
}

interface PendingAuthSession {
  session: string;
  action: 'enroll' | 'verify';
  ecdhPrivateKey: CryptoKey;
  vaultId: string;
  rawVaultKey?: Uint8Array;
  deviceId?: string;
  prfSalt?: Uint8Array;
  envelope?: DeviceBiometricEnvelope;
  /** RP ID and origin the ceremony is pinned to. */
  rpId: string;
  origin: string;
  /**
   * The WebAuthn challenge GENERATED BY THE PLUGIN for this ceremony.
   *
   * SECURITY: the relying party must be the one that picks the challenge,
   * otherwise it cannot verify it and the assertion could be replayed. The
   * challenge travels to the browser inside the URL fragment and MUST be used
   * verbatim by the WebAuthn ceremony.
   */
  challenge: Uint8Array;
  resolve: (value: any) => void;
  reject: (reason: any) => void;
  timeoutTimer: any;
}

/**
 * Computes the *binding* of a vault id that travels to the browser.
 *
 * SECURITY: the vault id itself is a secret-ish identifier (it is derived
 * from the Argon2 salt of the vault) and it must not be exposed to a remote
 * page. A SHA-256 digest is enough: it is used only to bind the AAD of the
 * bridge message, never as a key.
 */
function vaultBinding(vaultId: string): string {
  return sha256HexSync(`mysecret-bridge-vault:${vaultId}`);
}

export class ExternalBridgeProvider implements BiometricProvider {
  public readonly type = 'external-bridge';
  public readonly name = 'Puente WebAuthn Móvil (Huella en Navegador)';

  private bridgeUrl: string = '';
  private pendingSession: PendingAuthSession | null = null;

  constructor(bridgeUrl?: string) {
    if (bridgeUrl) {
      this.setBridgeUrl(bridgeUrl);
    }
  }

  public setBridgeUrl(url: string): void {
    // SECURITY: the URL is validated here as well, because the provider can
    // be configured from code paths other than the settings tab.
    const validation = validateBridgeUrl(url);
    this.bridgeUrl = validation.valid ? validation.url : '';
  }

  public getBridgeUrl(): string {
    return this.bridgeUrl;
  }

  /**
   * Available if a valid HTTPS bridge URL has been configured.
   */
  public async isAvailable(): Promise<boolean> {
    if (!this.bridgeUrl) return false;
    try {
      const parsed = new URL(this.bridgeUrl);
      return parsed.protocol === 'https:' || parsed.hostname === 'localhost';
    } catch {
      return false;
    }
  }

  /**
   * Returns the RP ID and the origin of the configured bridge.
   *
   * SECURITY: both are PINNED in the biometric envelope, so an envelope can
   * only ever be used from the exact origin where it was enrolled. Without
   * this, a sibling subdomain sharing the same registrable domain could
   * replay a credential enrolled for another host.
   */
  private getRelyingParty(): { rpId: string; origin: string } {
    const parsed = new URL(this.bridgeUrl);
    return {
      rpId: computeRpId(parsed.hostname),
      origin: computeOrigin(this.bridgeUrl)
    };
  }

  /**
   * Builds the Additional Authenticated Data of the bridge envelope.
   *
   * It binds the ciphertext to the protocol version, the session, the action
   * and the vault id, so a captured message cannot be replayed into another
   * session, another action or another vault.
   *
   * SECURITY: the vault id is NEVER sent to the browser in the clear. Only a
   * SHA-256 *binding* of it travels in the URL fragment, and the browser
   * echoes that binding back. The plugin always recomputes the binding
   * itself, so a manipulated value cannot change the AAD.
   */
  private buildBridgeAad(session: string, action: 'enroll' | 'verify', vaultId: string): string {
    return `mysecret-bridge:v${BRIDGE_PROTOCOL_VERSION}:${action}:${session}:${vaultBinding(vaultId)}`;
  }

  /**
   * Cancels any active pending session.
   */
  public cancelPendingSession(): void {
    if (this.pendingSession) {
      clearTimeout(this.pendingSession.timeoutTimer);
      if (this.pendingSession.rawVaultKey) {
        zeroize(this.pendingSession.rawVaultKey);
      }
      this.pendingSession.reject(new Error('Autenticación cancelada por el usuario.'));
      this.pendingSession = null;
    }
  }

  public hasPendingSession(): boolean {
    return this.pendingSession !== null;
  }

  /**
   * Handles incoming `obsidian://mysecret-auth` parameters.
   * Returns true if the callback was claimed and handled.
   */
  public async handleProtocolCallback(params: Record<string, string>): Promise<boolean> {
    if (!this.pendingSession) {
      return false;
    }

    const { session, error, pub, iv, tag, data } = params;

    if (!session) {
      return false;
    }

    // SECURITY: the session token is compared in CONSTANT TIME. A short
    // circuiting comparison leaks the matching prefix length through timing
    // and would allow an attacker to brute force the token byte by byte.
    const currentSession = this.pendingSession;
    const expectedToken = currentSession.session;
    let sessionBytes: Uint8Array;
    let expectedBytes: Uint8Array;
    try {
      sessionBytes = hexToBytesStrict(session.toLowerCase());
      expectedBytes = hexToBytesStrict(expectedToken.toLowerCase());
    } catch {
      return false;
    }
    if (
      sessionBytes.length !== expectedBytes.length ||
      !constantTimeEqual(sessionBytes, expectedBytes)
    ) {
      // Not for our current session
      return false;
    }

    this.pendingSession = null;
    clearTimeout(currentSession.timeoutTimer);

    if (error) {
      if (currentSession.rawVaultKey) zeroize(currentSession.rawVaultKey);
      currentSession.reject(new Error(decodeURIComponent(error)));
      return true;
    }

    try {
      if (!pub || !iv || !tag || !data) {
        throw new Error('Parámetros de respuesta incompletos del puente biométrico.');
      }

      // 1. Validate the shape of every parameter BEFORE using it.
      const browserPubBytes = hexToBytesStrict(pub);
      if (browserPubBytes.length !== 65) {
        throw new Error('La clave pública del puente no tiene el formato esperado.');
      }
      const ivBytes = hexToBytesStrict(iv);
      if (ivBytes.length !== 12) {
        throw new Error('El vector de inicialización del puente no es válido.');
      }
      const tagBytes = hexToBytesStrict(tag);
      if (tagBytes.length !== 16) {
        throw new Error('La etiqueta de autenticación del puente no es válida.');
      }
      const cipherBytes = hexToBytesStrict(data);
      if (cipherBytes.length === 0) {
        throw new Error('El mensaje del puente está vacío.');
      }

      // 2. Import browser's P-256 public key (raw 65 bytes)
      const browserPubKey = await window.crypto.subtle.importKey(
        'raw',
        browserPubBytes as BufferSource,
        { name: 'ECDH', namedCurve: 'P-256' },
        false,
        []
      );

      // 3. Derive the shared secret and run it through HKDF-SHA256.
      //    NIST SP 800-56A requires a KDF: the raw X coordinate of an ECDH
      //    exchange must never be used directly as a symmetric key.
      const sharedSecret = await window.crypto.subtle.deriveBits(
        { name: 'ECDH', public: browserPubKey },
        currentSession.ecdhPrivateKey,
        256
      );
      const bridgeAad = this.buildBridgeAad(
        currentSession.session,
        currentSession.action,
        currentSession.vaultId
      );
      const sharedKey = await deriveAesKeyFromSecret(
        new Uint8Array(sharedSecret),
        `mysecret-bridge:${currentSession.session}`,
        bridgeAad
      );

      // 4. Decrypt payload.
      //    The AAD is bound to the protocol version, the action, the session
      //    and the vault (via its one-way binding), so a captured ciphertext
      //    cannot be replayed into another context.
      const aadBytes = stringToBytes(bridgeAad) as BufferSource;
      const fullEncBytes = new Uint8Array(cipherBytes.length + tagBytes.length);
      fullEncBytes.set(cipherBytes, 0);
      fullEncBytes.set(tagBytes, cipherBytes.length);

      const decryptedBuffer = await window.crypto.subtle.decrypt(
        { name: 'AES-GCM', iv: ivBytes as BufferSource, additionalData: aadBytes, tagLength: 128 },
        sharedKey,
        fullEncBytes
      );

      const payloadStr = new TextDecoder().decode(decryptedBuffer);
      let payload: BridgePayload;
      try {
        payload = JSON.parse(payloadStr);
      } catch {
        throw new Error('El mensaje del puente no tiene un formato válido.');
      }

      // 5. Validate the payload: protocol version, session, action.
      if (!payload || typeof payload !== 'object') {
        throw new Error('El mensaje del puente está vacío.');
      }
      if (payload.v !== BRIDGE_PROTOCOL_VERSION) {
        throw new Error(
          `Versión del protocolo del puente no soportada (${payload.v}). Actualiza el puente.`
        );
      }
      if (payload.session !== currentSession.session) {
        throw new Error('El token de sesión no coincide: posible ataque de repetición.');
      }
      if (payload.action !== currentSession.action) {
        throw new Error('La acción del puente no coincide con la solicitada.');
      }
      if (!payload.prfSecret || typeof payload.prfSecret !== 'string') {
        throw new Error('No se recibió el secreto biométrico PRF.');
      }

      // 6. Normalize the PRF secret. A short/empty secret is REJECTED: an
      //    empty secret would hash to a PUBLIC constant, making the wrapping
      //    key computable by anybody.
      const prfSecretBytes = normalizePrfOutput(payload.prfSecret);

      if (currentSession.action === 'enroll') {
        // Enrolling: wrap the rawVaultKey using PRF secret
        const rawVaultKey = currentSession.rawVaultKey!;
        const vaultId = currentSession.vaultId;
        const deviceId = currentSession.deviceId!;
        const prfSalt = currentSession.prfSalt!;

        // The credential public key MUST be present and well formed before it
        // is persisted: a broken key would make every future unlock fail
        // (and, worse, would silently disable the signature verification).
        if (!payload.publicKey) {
          throw new Error('El puente no devolvió la clave pública de la credencial.');
        }
        const publicKeyBytes = base64ToBytes(payload.publicKey);
        if (publicKeyBytes.length === 0) {
          throw new Error('La clave pública de la credencial no es válida.');
        }
        if (!payload.credentialId) {
          throw new Error('El puente no devolvió el identificador de la credencial.');
        }

        const digest = await window.crypto.subtle.digest('SHA-256', prfSecretBytes as BufferSource);
        const wrapKey = await importAesKey(new Uint8Array(digest));
        const enc = await encryptAesGcm(rawVaultKey, wrapKey, biometricAad(this.type, vaultId));
        zeroize(prfSecretBytes);

        const keyCheck = await sha256Hex(rawVaultKey);
        zeroize(rawVaultKey);

        const now = Date.now();
        const envelope: DeviceBiometricEnvelope = {
          version: BIOMETRIC_ENVELOPE_VERSION,
          deviceId,
          providerType: this.type,
          mode: 'external-bridge',
          createdAt: now,
          updatedAt: now,
          iv: bytesToHex(enc.iv),
          tag: bytesToHex(enc.tag),
          ciphertext: bytesToHex(enc.ciphertext),
          keyCheck,
          credentialId: payload.credentialId,
          credentialPublicKey: payload.publicKey,
          prfSalt: bytesToHex(prfSalt),
          // The RP ID and the origin are pinned so that this envelope can
          // only be used from the very origin where it was enrolled.
          rpId: currentSession.rpId,
          origin: currentSession.origin
        } as DeviceBiometricEnvelope;

        currentSession.resolve(envelope);
      } else {
        // Verifying: the ASSERTION must be cryptographically valid.
        const envelope = currentSession.envelope!;
        const vaultId = currentSession.vaultId;

        if (!payload.assertion) {
          throw new Error('El puente no devolvió la aserción biométrica verificable.');
        }
        if (!envelope.credentialPublicKey) {
          throw new Error(
            'El sobre biométrico no contiene la clave pública de la credencial: re-enrolar.'
          );
        }
        if (
          envelope.rpId &&
          envelope.origin &&
          (envelope.rpId !== currentSession.rpId || envelope.origin !== currentSession.origin)
        ) {
          throw new Error(
            'El origen del puente no coincide con el del enrolamiento: re-enrolar la huella.'
          );
        }

        const assertion = {
          id: payload.credentialId,
          response: {
            authenticatorData: base64ToBytes(payload.assertion.authenticatorData),
            clientDataJSON: base64ToBytes(payload.assertion.clientDataJSON),
            signature: base64ToBytes(payload.assertion.signature),
            userVerified: payload.assertion.userVerified === true
          }
        };

        // SECURITY: this is the check that makes the whole bridge sound. The
        // PRF secret is only trusted because the ENROLLED AUTHENTICATOR
        // signed this assertion after a user-verifying ceremony.
        //
        // The expected challenge is the one GENERATED BY THE PLUGIN, never
        // the one reported by the browser: the browser is the untrusted party
        // here, so accepting its own challenge value would make the replay
        // protection useless.
        await verifyWebAuthnAssertion(assertion, {
          expectedCredentialId: envelope.credentialId || payload.credentialId,
          expectedChallenge: currentSession.challenge,
          expectedOrigin: envelope.origin || currentSession.origin,
          expectedRpId: envelope.rpId || currentSession.rpId,
          publicKeySpkiBase64: envelope.credentialPublicKey
        });

        // Decrypt the envelope ciphertext using PRF secret
        const aad = biometricAad(this.type, vaultId);
        const digest = await window.crypto.subtle.digest('SHA-256', prfSecretBytes as BufferSource);
        const wrapKey = await importAesKey(new Uint8Array(digest));
        zeroize(prfSecretBytes);

        const rawKey = await decryptAesGcm(
          hexToBytes(envelope.ciphertext),
          wrapKey,
          hexToBytes(envelope.iv),
          hexToBytes(envelope.tag),
          aad
        );

        if (envelope.keyCheck) {
          const check = await sha256Hex(rawKey);
          if (!constantTimeHexEqual(check, envelope.keyCheck)) {
            zeroize(rawKey);
            throw new Error('Error de integridad: la clave descifrada no coincide.');
          }
        }

        currentSession.resolve(rawKey);
      }
      return true;
    } catch (err: any) {
      if (currentSession.rawVaultKey) zeroize(currentSession.rawVaultKey);
      currentSession.reject(err);
      return true;
    }
  }

  public async enroll(
    rawVaultKey: Uint8Array,
    deviceId: string,
    vaultId: string
  ): Promise<DeviceBiometricEnvelope> {
    if (!await this.isAvailable()) {
      throw new Error(
        'La URL del puente biométrico no está configurada o no es válida. Ve a Ajustes > MySecret para configurarla.'
      );
    }

    this.cancelPendingSession();

    // 1. Generate ephemeral ECDH keypair.
    //    The private key is NOT extractable: it can never leak to the
    //    renderer heap, to a crash dump or to a malicious plugin.
    const ecdhKeyPair = await window.crypto.subtle.generateKey(
      { name: 'ECDH', namedCurve: 'P-256' },
      false,
      ['deriveBits']
    );

    const rawPub = await window.crypto.subtle.exportKey('raw', ecdhKeyPair.publicKey);
    const pubHex = bytesToHex(new Uint8Array(rawPub));

    // 2. Generate random 32-byte session token
    const sessionBytes = new Uint8Array(32);
    window.crypto.getRandomValues(sessionBytes);
    const sessionToken = bytesToHex(sessionBytes);

    // 3. Generate random 32-byte PRF salt
    const prfSalt = new Uint8Array(32);
    window.crypto.getRandomValues(prfSalt);
    const saltHex = bytesToHex(prfSalt);

    // Copy rawVaultKey for safe in-memory retention until callback
    const rawKeyCopy = new Uint8Array(rawVaultKey);

    // The RP ID and the origin are pinned for this enrollment.
    const { rpId, origin } = this.getRelyingParty();

    // 4. Generate the WebAuthn challenge.
    //    The relying party (the plugin) MUST choose the challenge so it can
    //    verify it later and prevent replay attacks.
    const challenge = new Uint8Array(32);
    window.crypto.getRandomValues(challenge);

    return new Promise<DeviceBiometricEnvelope>((resolve, reject) => {
      const timeoutTimer = setTimeout(() => {
        if (this.pendingSession?.session === sessionToken) {
          this.cancelPendingSession();
        }
      }, BRIDGE_TIMEOUT_MS);

      this.pendingSession = {
        session: sessionToken,
        action: 'enroll',
        ecdhPrivateKey: ecdhKeyPair.privateKey,
        vaultId,
        rawVaultKey: rawKeyCopy,
        deviceId,
        prfSalt,
        rpId,
        origin,
        challenge,
        resolve,
        reject,
        timeoutTimer
      };

      // Construct bridge URL with parameters in hash.
      // The vault binding is a one-way digest: the real vault id never leaves
      // the plugin.
      const targetUrl =
        `${this.bridgeUrl}/#v=${BRIDGE_PROTOCOL_VERSION}` +
        `&action=enroll&session=${sessionToken}&pub=${pubHex}&salt=${saltHex}` +
        `&challenge=${bytesToHex(challenge)}` +
        `&rpId=${encodeURIComponent(rpId)}` +
        `&vb=${vaultBinding(vaultId)}`;

      // Open in system browser
      this.openInSystemBrowser(targetUrl);
    });
  }

  public async verifyAndDecrypt(
    envelope: DeviceBiometricEnvelope,
    vaultId: string
  ): Promise<Uint8Array | null> {
    if (!await this.isAvailable()) {
      console.warn('[MySecret] Puente biométrico no configurado.');
      return null;
    }

    if (!envelope.prfSalt || !envelope.credentialId) {
      console.warn('[MySecret] Sobre biométrico incompleto: falta PRF salt o credential ID.');
      return null;
    }

    this.cancelPendingSession();

    // 1. Generate ephemeral ECDH keypair (non extractable private key).
    const ecdhKeyPair = await window.crypto.subtle.generateKey(
      { name: 'ECDH', namedCurve: 'P-256' },
      false,
      ['deriveBits']
    );

    const rawPub = await window.crypto.subtle.exportKey('raw', ecdhKeyPair.publicKey);
    const pubHex = bytesToHex(new Uint8Array(rawPub));

    // 2. Generate random 32-byte session token
    const sessionBytes = new Uint8Array(32);
    window.crypto.getRandomValues(sessionBytes);
    const sessionToken = bytesToHex(sessionBytes);

    const { rpId, origin } = this.getRelyingParty();

    // 3. Generate the WebAuthn challenge (the relying party picks it).
    const challenge = new Uint8Array(32);
    window.crypto.getRandomValues(challenge);

    return new Promise<Uint8Array | null>((resolve, reject) => {
      const timeoutTimer = setTimeout(() => {
        if (this.pendingSession?.session === sessionToken) {
          this.cancelPendingSession();
        }
      }, BRIDGE_TIMEOUT_MS);

      this.pendingSession = {
        session: sessionToken,
        action: 'verify',
        ecdhPrivateKey: ecdhKeyPair.privateKey,
        vaultId,
        envelope,
        rpId,
        origin,
        challenge,
        resolve,
        reject: (err) => {
          console.warn('[MySecret] Error en verificación externa:', err);
          resolve(null);
        },
        timeoutTimer
      };

      const targetUrl =
        `${this.bridgeUrl}/#v=${BRIDGE_PROTOCOL_VERSION}` +
        `&action=verify&session=${sessionToken}&pub=${pubHex}` +
        `&salt=${envelope.prfSalt}` +
        `&credentialId=${encodeURIComponent(envelope.credentialId || '')}` +
        `&rpId=${encodeURIComponent(rpId)}` +
        `&challenge=${bytesToHex(challenge)}` +
        `&vb=${vaultBinding(vaultId)}`;
      this.openInSystemBrowser(targetUrl);
    });
  }

  private openInSystemBrowser(url: string): void {
    // In Capacitor Android, window.open(url, '_system') opens the native external browser (Chrome)
    if (typeof window !== 'undefined') {
      try {
        const opened = window.open(url, '_system');
        if (!opened) {
          window.open(url, '_blank');
        }
      } catch {
        window.open(url, '_blank');
      }
    }
  }
}
